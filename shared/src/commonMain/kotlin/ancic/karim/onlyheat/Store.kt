package ancic.karim.onlyheat

import androidx.room3.ConstructedBy
import androidx.room3.Dao
import androidx.room3.Database
import androidx.room3.Entity
import androidx.room3.Insert
import androidx.room3.OnConflictStrategy
import androidx.room3.Query
import androidx.room3.RoomDatabase
import androidx.room3.RoomDatabaseConstructor
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import com.russhwolf.settings.Settings
import kotlin.time.Duration
import kotlin.time.Duration.Companion.hours

// Local history: the server only keeps ~25 h, so every reading we see is kept here for week/month views.

@Entity(primaryKeys = ["roomId", "time"])
data class Reading(val roomId: String, val time: Long, val measured: Double?, val target: Double?) // "current" and "temp" are SQL keywords

@Dao
interface ReadingDao {
    @Insert(onConflict = OnConflictStrategy.IGNORE) // a reading never changes once logged
    suspend fun insert(readings: List<Reading>)

    /** [roomId]'s readings since [from], averaged into [bucket]-second slots, oldest first. */
    @Query("SELECT roomId, time / :bucket * :bucket AS time, AVG(measured) AS measured, AVG(target) AS target FROM Reading WHERE roomId = :roomId AND time >= :from GROUP BY time / :bucket ORDER BY time")
    suspend fun averaged(roomId: String, from: Long, bucket: Long): List<Reading>

    @Query("SELECT MIN(time) FROM Reading")
    suspend fun oldest(): Long?
}

@Database(entities = [Reading::class], version = 1)
@ConstructedBy(HistoryDbConstructor::class)
abstract class HistoryDb : RoomDatabase() {
    abstract fun readings(): ReadingDao
}

@Suppress("KotlinNoActualForExpect") // generated by the Room compiler
expect object HistoryDbConstructor : RoomDatabaseConstructor<HistoryDb> {
    override fun initialize(): HistoryDb
}

internal expect fun historyDbBuilder(): RoomDatabase.Builder<HistoryDb>

val history: ReadingDao by lazy { historyDbBuilder().setDriver(BundledSQLiteDriver()).build().readings() }

internal fun Reading.point() = Point(time, measured, target)

suspend fun storeLog(roomId: String, log: List<Point>) =
    history.insert(log.filter { it.time > 0 }.map { Reading(roomId, it.time, it.current, it.target) })

/**
 * Copies every room's last ~25 h from the server into [history], unless that was done within [every].
 * Has to run at least daily for gap-free history: the Android worker does, desktop/iOS only while the app is open.
 */
suspend fun syncHistory(api: HeatApi, key: String, s: Settings = Settings(), every: Duration = 6.hours) {
    val now = nowSeconds()
    if (now - s.getLong("history.synced", 0) < every.inWholeSeconds) return
    // One room at a time: the server relays to the controller serially, parallel calls time each other out.
    api.home(key).rooms.forEach { storeLog(it.id, api.roomLog(key, it.id)) }
    s.putLong("history.synced", now)
}
